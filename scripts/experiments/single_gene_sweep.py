#!/usr/bin/env python3
"""One classifier per gene: a specificity control that scales linearly instead of quadratically.

THE SCALING PROBLEM THIS SOLVES. The panel-based specificity control puts control genes INSIDE
the classifier's input, so adding a control means retraining, and a retrain changes the classifier,
so every other gene's Delta has to be remeasured for like-for-like. Adding the k-th control costs
a retrain plus k measurements, and the whole table has to be regenerated each time. At three
controls the panel/control comparison has n = 3 against n = 11 and cannot reach significance.

Training ONE classifier per gene removes the coupling. Each gene gets its own model, its own
accuracy and its own knockdown, and none of them depends on which other genes exist. Adding a gene
is O(1): train one small model, replay one set of scrambles, append one row. Nothing already
measured is invalidated.

WHAT IT MEASURES, AND WHAT IT DOES NOT. The panel knockdown measures RELIANCE -- a property of the
trained classifier, which depends on what else is in the panel. The single-gene knockdown measures
the response with reliance at its maximum: there is nothing to route to, so the classifier must use
this locus or fail. That is a different quantity and it does NOT replace the panel measurement the
paper's claim is about. For the specificity question it is arguably the better one, because a
control gene can be flat in a panel simply because panel genes crowd it out, and here nothing can.

Two readouts per gene, on the same footing for every gene:
    single-gene test accuracy   the information the window carries about the label
    single-gene |Delta|         the same 100 bp promoter scramble at maximal reliance

COST. Training only -- every biology_tss scramble for the fourteen built windows is already on
disk, so the knockdown step makes NO AlphaGenome calls. A single-gene model is 49,522 parameters
against the panel's 475,506, and its tensor view is ~1.6 GB against ~23 GB.

DISK. Each arm's tensor cache is ~1.6 GB and fourteen of them do not fit here. The sweep deletes
each arm's cache after that arm's knockdown is written, and only ever deletes a directory that
(a) did not exist before that arm started and (b) lives under the pigmentation datasets cache root.
Caches are regenerable by construction; filling this disk has already cost one experiment
(2026-08-31), which is why this is on by default. `--keep-cache` disables it.

Usage:
  python3 scripts/experiments/single_gene_sweep.py --write-configs          # configs only
  python3 scripts/experiments/single_gene_sweep.py --genes TPM2,SMCR8       # run two arms
  python3 scripts/experiments/single_gene_sweep.py                          # all built windows
  python3 scripts/experiments/single_gene_sweep.py --dry-run
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path("/home/breno/I2CA/genomics")
PY = "/home/breno/miniforge3/envs/genomics/bin/python3"
DATASET = Path("/dados/GENOMICS_DATA/v1/1kG_high_coverage")
BASE_CONFIG = REPO_ROOT / "configs/predictors/genotype_based/pigmentation/pigmentation_binary_no_alignment.yaml"
CONFIG_DIR = REPO_ROOT / "configs/predictors/genotype_based/pigmentation/single_gene"
CACHE_ROOT = REPO_ROOT / "results/cache/genotype_based_predictor/pigmentation/datasets"
KO_DIR = REPO_ROOT / "results/genotype_based_predictor/knockout_bulk"
LOG_DIR = REPO_ROOT / "results/genotype_based_predictor/logs"
RUN_NAME = ("cnn2_pigmentation_rna_seq_H1+H2_raw_center_crop_32768_log_"
            "s1k6x32f16_s2f32_s3f64_gpavg_fc256_L100-40_relu_0.5_adam")
PANEL = ["MC1R", "TYRP1", "TYR", "SLC45A2", "DDB1", "EDAR", "MFSD12", "OCA2", "HERC2", "SLC24A5", "TCHH"]
CONTROLS = ["TPM2", "SMCR8", "PSMC4"]
# Written by hand before the sweep existed; their configs live outside CONFIG_DIR.
LEGACY = {"SLC24A5", "TYR"}
EXPECTED_INDIVIDUALS = 1072
MIN_FREE_GB = 8

NOTE = """metadata:
  note: >
    SINGLE-GENE ARM -- {GENE} alone, generated by scripts/experiments/single_gene_sweep.py.
    Identical to pigmentation_binary_no_alignment.yaml in every respect (layout, crop,
    ontologies, architecture, optimisation, split, seed) except genes_to_use (one gene),
    results_dir and run_name.

    WHY ONE MODEL PER GENE. The panel-based specificity control couples every gene to
    every other: a control gene has to be inside the classifier's input to have any
    Delta, so adding one means retraining, and a retrain invalidates the other genes'
    published Delta values. Adding the k-th control costs a retrain plus k
    remeasurements. One classifier per gene removes the coupling entirely -- each arm is
    independent, adding a gene is O(1), and nothing already measured is invalidated.

    WHAT THIS MEASURES. Not reliance in a panel, which is what the paper's claim is
    about and which this does not replace. With one gene in the input there is nothing
    to route to, so the accuracy measures the INFORMATION the window carries about the
    label and the knockdown measures the same 100 bp promoter scramble with reliance
    pinned at its maximum. A control gene cannot be flat here merely because panel genes
    crowded it out.

    ISOLATED results_dir. The run name is derived from architecture and layout only and
    does NOT include the gene list, so every raw_center_crop CNN2 arm resolves to the
    same directory name. A shared results_dir silently overwrites the published run;
    that happened on 2026-09-06 and destroyed a checkpoint.

"""


def _log(m):
    print(f"[{datetime.now(timezone.utc).isoformat()}] {m}", flush=True)


def free_gb(path=REPO_ROOT):
    st = shutil.disk_usage(path)
    return st.free / 1024 ** 3


def write_config(gene: str) -> Path:
    """Generate the arm's config from the published baseline, changing exactly three fields."""
    src = BASE_CONFIG.read_text()
    s = NOTE.replace("{GENE}", gene) + src[src.index("dataset_input:"):]
    old_genes = s[s.index("  genes_to_use:"):s.index("  ontology_terms:")]
    s = s.replace(old_genes, f'  genes_to_use:\n    - "{gene}"\n')
    s = s.replace('  results_dir: "results/genotype_based_predictor/runs"',
                  f'  results_dir: "results/genotype_based_predictor/runs_single_gene_{gene.lower()}"')
    s = s.replace('  run_name: "pigmentation-binary-no-alignment"',
                  f'  run_name: "pigmentation-binary-single-gene-{gene.lower()}"')
    CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    out = CONFIG_DIR / f"pigmentation_binary_single_{gene.lower()}.yaml"
    out.write_text(s)
    return out


def verify_config(path: Path, gene: str):
    """Refuse to run an arm whose config drifts from the baseline in more than the three fields."""
    import yaml
    base = yaml.safe_load(BASE_CONFIG.read_text())
    cfg = yaml.safe_load(path.read_text())
    diffs = []

    def walk(a, b, pre=""):
        for k in sorted(set(a) | set(b)):
            if k == "metadata":
                continue
            p = f"{pre}.{k}" if pre else k
            va, vb = a.get(k, "<missing>"), b.get(k, "<missing>")
            if isinstance(va, dict) and isinstance(vb, dict):
                walk(va, vb, p)
            elif va != vb:
                diffs.append(p)

    walk(base, cfg)
    allowed = {"dataset_input.genes_to_use", "dataset_input.results_dir", "wandb.run_name"}
    extra = set(diffs) - allowed
    if extra:
        raise SystemExit(f"ABORT: {path} drifts from the baseline in {sorted(extra)}")
    if cfg["dataset_input"]["genes_to_use"] != [gene]:
        raise SystemExit(f"ABORT: {path} gene list is {cfg['dataset_input']['genes_to_use']}")
    if f"runs_single_gene_{gene.lower()}" not in cfg["dataset_input"]["results_dir"]:
        raise SystemExit(f"ABORT: {path} has no isolated results_dir")
    return sorted(diffs)


def config_for(gene: str) -> Path:
    if gene in LEGACY:
        p = REPO_ROOT / ("configs/predictors/genotype_based/pigmentation/"
                         f"pigmentation_binary_no_alignment_single_{gene.lower()}.yaml")
        if p.exists():
            return p
    return CONFIG_DIR / f"pigmentation_binary_single_{gene.lower()}.yaml"


def views() -> set:
    return {p.name for p in CACHE_ROOT.iterdir()} if CACHE_ROOT.exists() else set()


def run(cmd, log_path):
    with open(log_path, "w", encoding="utf-8") as fh:
        return subprocess.run(cmd, stdout=fh, stderr=subprocess.STDOUT, cwd=REPO_ROOT).returncode


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--genes", default=None, help="comma-separated; default: every built window")
    ap.add_argument("--write-configs", action="store_true", help="generate configs and exit")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--keep-cache", action="store_true",
                    help="do not delete each arm's ~1.6 GB tensor view after its knockdown")
    ap.add_argument("--skip-done", action="store_true", default=True)
    args = ap.parse_args()

    built = sorted(p.name for p in (DATASET / "individuals" / "HG00096" / "windows").iterdir()
                   if p.is_dir())
    genes = [g.strip().upper() for g in args.genes.split(",")] if args.genes else built
    missing = [g for g in genes if g not in built]
    if missing:
        raise SystemExit(f"ABORT: no built window for {missing}. Build it first "
                         "(~2,144 AlphaGenome calls per gene for 1072 individuals x 2 haplotypes).")

    LOG_DIR.mkdir(parents=True, exist_ok=True)
    _log(f"{len(genes)} arms: {', '.join(genes)}")

    for g in genes:
        cfg = config_for(g)
        if not cfg.exists() or (args.write_configs and g not in LEGACY):
            cfg = write_config(g)
            _log(f"{g:<9} wrote {cfg.relative_to(REPO_ROOT)}")
        drift = verify_config(cfg, g)
        _log(f"{g:<9} config OK, drift from baseline = {drift}")
    if args.write_configs:
        return 0

    for g in genes:
        arm = g.lower()
        cfg = config_for(g)
        run_dir = REPO_ROOT / f"results/genotype_based_predictor/runs_single_gene_{arm}" / RUN_NAME
        ko_csv = KO_DIR / f"pigmentation_test_split_knockout_single_{arm}.csv"
        n_win = len(list((DATASET / "individuals").glob(f"*/windows/{g}")))
        if n_win < EXPECTED_INDIVIDUALS:
            _log(f"{g:<9} SKIP: only {n_win}/{EXPECTED_INDIVIDUALS} windows built")
            continue
        if args.skip_done and ko_csv.exists():
            _log(f"{g:<9} SKIP: {ko_csv.name} already present")
            continue
        if free_gb() < MIN_FREE_GB:
            _log(f"ABORT: {free_gb():.1f} GB free, need >= {MIN_FREE_GB}")
            return 1
        if args.dry_run:
            _log(f"{g:<9} DRY RUN: would train {cfg.name}, test, replay, then free its cache")
            continue

        stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        before = views()
        t0 = time.monotonic()

        _log(f"{g:<9} training ({free_gb():.1f} GB free)...")
        rc = run([PY, "-m", "genomics", "genotype", "train", str(cfg)],
                 LOG_DIR / f"sweep_{arm}_{stamp}.train.log")
        if rc != 0:
            _log(f"{g:<9} FAILED training (rc={rc}); see sweep_{arm}_{stamp}.train.log")
            continue
        rc = run([PY, "-m", "genomics", "genotype", "test", str(cfg)],
                 LOG_DIR / f"sweep_{arm}_{stamp}.test.log")
        if rc != 0:
            _log(f"{g:<9} FAILED test (rc={rc})")
            continue
        acc = None
        tj = run_dir / "test_best_accuracy_results.json"
        if tj.exists():
            acc = json.loads(tj.read_text())["weighted_accuracy"]

        _log(f"{g:<9} knockdown replay (cached scrambles, no API calls)...")
        rc = run([PY, "scripts/experiments/single_gene_knockdown_replay.py", "--arm", arm],
                 LOG_DIR / f"sweep_{arm}_{stamp}.replay.log")
        if rc != 0:
            _log(f"{g:<9} FAILED replay (rc={rc}); keeping the cache for diagnosis")
            continue

        freed = 0.0
        if not args.keep_cache:
            new = views() - before
            for name in new:
                d = CACHE_ROOT / name
                # only a directory this arm created, and only under the pigmentation cache root
                if d.is_dir() and d.resolve().parent == CACHE_ROOT.resolve():
                    sz = sum(f.stat().st_size for f in d.rglob("*") if f.is_file()) / 1024 ** 3
                    shutil.rmtree(d)
                    freed += sz
        _log(f"{g:<9} DONE in {(time.monotonic()-t0)/60:.1f} min | test acc = "
             f"{acc if acc is None else f'{acc:.4f}'} | freed {freed:.1f} GB | "
             f"{free_gb():.1f} GB free")

    _log("sweep finished. Aggregate with scripts/experiments/single_gene_sweep_report.py")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
